import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Mirrors supported pasteboard contents while a clipboard-capable peer is connected.
/// All pasteboard access and state transitions happen on the main thread.
@MainActor
final class ClipboardSync {
    private enum Candidate {
        case ready(ClipboardFormat, Data)
        case tiff(Data)
    }

    private struct TIFFConversion {
        let data: Data
        let revision: ClipboardRevision
        let generation: UInt64
        let changeCount: Int
    }

    private static let transientTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]
    private static let maximumTIFFBytes = 128 * 1_024 * 1_024

    private let pasteboard: NSPasteboard
    private let origin: UUID
    private let conversionQueue: DispatchQueue
    private let schedulesTimer: Bool
    private var timer: Timer?
    private var send: ((ClipboardPayload) -> Void)?
    private var observedChangeCount = 0
    private var lamportCounter: UInt64 = 0
    private var currentRevision: ClipboardRevision?
    private var locallySendableRevision: ClipboardRevision?
    private var pendingConversionRevision: ClipboardRevision?
    private var conversionInFlight = false
    private var queuedConversion: TIFFConversion?
    private var generation: UInt64 = 0
    private var pendingPaste: ((ClipboardRevision?) -> Void)?

    var onRemoteResolved: ((ClipboardRevision) -> Void)?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        origin = UUID()
        conversionQueue = DispatchQueue(
            label: "com.sunny.thunderlink.clipboard-conversion",
            qos: .utility
        )
        schedulesTimer = true
    }

    init(
        pasteboard: NSPasteboard,
        origin: UUID,
        conversionQueue: DispatchQueue,
        schedulesTimer: Bool
    ) {
        self.pasteboard = pasteboard
        self.origin = origin
        self.conversionQueue = conversionQueue
        self.schedulesTimer = schedulesTimer
    }

    func start(send: @escaping (ClipboardPayload) -> Void) {
        precondition(Thread.isMainThread)
        let resolutionHandler = onRemoteResolved
        stop()
        onRemoteResolved = resolutionHandler
        self.send = send
        observedChangeCount = pasteboard.changeCount
        currentRevision = nil
        generation &+= 1
        guard schedulesTimer else { return }
        let timer = Timer(timeInterval: 0.2, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func stop() {
        precondition(Thread.isMainThread)
        timer?.invalidate()
        timer = nil
        send = nil
        currentRevision = nil
        locallySendableRevision = nil
        pendingConversionRevision = nil
        queuedConversion = nil
        generation &+= 1
        finishPastePreparation(with: nil)
        onRemoteResolved = nil
    }

    func poll() {
        precondition(Thread.isMainThread)
        guard send != nil, pasteboard.changeCount != observedChangeCount else { return }
        observeLocalChange()
    }

    func receive(_ payload: ClipboardPayload) {
        precondition(Thread.isMainThread)
        guard send != nil, Self.isValid(payload) else { return }

        // A copy made locally just before this network callback must participate
        // in conflict resolution rather than being silently overwritten.
        if pasteboard.changeCount != observedChangeCount {
            observeLocalChange()
        }
        lamportCounter = max(lamportCounter, payload.revision.counter)
        if let currentRevision, payload.revision <= currentRevision {
            onRemoteResolved?(payload.revision)
            return
        }

        generation &+= 1
        queuedConversion = nil
        locallySendableRevision = nil
        pendingConversionRevision = nil
        finishPastePreparation(with: nil)
        guard write(payload) else { return }
        observedChangeCount = pasteboard.changeCount
        currentRevision = payload.revision
        onRemoteResolved?(payload.revision)
    }

    /// Flushes an unobserved local copy before Command-V is sent to the peer.
    /// TIFF screenshots finish asynchronously, so the caller can wait for the
    /// returned revision to be acknowledged by the receiving Mac.
    func prepareForPaste(_ completion: @escaping (ClipboardRevision?) -> Void) {
        precondition(Thread.isMainThread)
        guard send != nil else {
            completion(nil)
            return
        }
        poll()
        if let revision = locallySendableRevision, revision == currentRevision {
            completion(revision)
            return
        }
        guard let pendingConversionRevision,
              pendingConversionRevision == currentRevision else {
            completion(nil)
            return
        }

        finishPastePreparation(with: nil)
        pendingPaste = completion
    }

    private func observeLocalChange() {
        guard send != nil else { return }
        observedChangeCount = pasteboard.changeCount
        queuedConversion = nil
        guard let candidate = candidateFromPasteboard() else {
            currentRevision = nil
            locallySendableRevision = nil
            pendingConversionRevision = nil
            generation &+= 1
            finishPastePreparation(with: nil)
            return
        }

        lamportCounter &+= 1
        let revision = ClipboardRevision(counter: lamportCounter, origin: origin)
        currentRevision = revision
        locallySendableRevision = nil
        pendingConversionRevision = nil
        generation &+= 1
        let capturedGeneration = generation

        switch candidate {
        case .ready(let format, let data):
            emit(format: format, data: data, revision: revision, generation: capturedGeneration)
        case .tiff(let data):
            pendingConversionRevision = revision
            schedule(TIFFConversion(
                data: data,
                revision: revision,
                generation: capturedGeneration,
                changeCount: observedChangeCount
            ))
        }
    }

    private func schedule(_ conversion: TIFFConversion) {
        if conversionInFlight {
            queuedConversion = conversion
            return
        }
        conversionInFlight = true
        conversionQueue.async { [weak self] in
            let png = Self.pngData(fromTIFF: conversion.data)
            DispatchQueue.main.async {
                guard let self else { return }
                self.finish(conversion, png: png)
            }
        }
    }

    private func finish(_ conversion: TIFFConversion, png: Data?) {
        conversionInFlight = false
        defer {
            if let next = queuedConversion {
                queuedConversion = nil
                schedule(next)
            }
        }
        // Check session ownership before touching the pasteboard. A conversion
        // may complete after disconnect or after a newer local copy supersedes it.
        guard send != nil, generation == conversion.generation else { return }
        if pasteboard.changeCount != conversion.changeCount {
            observeLocalChange()
            return
        }
        guard let png else {
            if pendingConversionRevision == conversion.revision {
                pendingConversionRevision = nil
                finishPastePreparation(with: conversion.revision)
            }
            return
        }
        emit(
            format: .png,
            data: png,
            revision: conversion.revision,
            generation: conversion.generation
        )
    }

    private func emit(
        format: ClipboardFormat,
        data: Data,
        revision: ClipboardRevision,
        generation capturedGeneration: UInt64
    ) {
        guard send != nil,
              generation == capturedGeneration,
              currentRevision == revision,
              data.count <= ClipboardPayload.maxBytes else { return }
        let payload = ClipboardPayload(revision: revision, format: format, data: data)
        guard Self.isValid(payload) else { return }
        send?(payload)
        locallySendableRevision = revision
        pendingConversionRevision = nil
        finishPastePreparation(with: revision)
    }

    private func finishPastePreparation(with revision: ClipboardRevision?) {
        let completion = pendingPaste
        pendingPaste = nil
        completion?(revision)
    }

    private func candidateFromPasteboard() -> Candidate? {
        guard let item = pasteboard.pasteboardItems?.first else { return nil }
        let types = Set(item.types)
        guard types.isDisjoint(with: Self.transientTypes),
              !types.contains(.fileURL) else { return nil }

        if let png = item.data(forType: .png),
           !png.isEmpty,
           png.count <= ClipboardPayload.maxBytes,
           Self.isValidImage(png, expectedType: UTType.png.identifier) {
            return .ready(.png, png)
        }
        if let tiff = item.data(forType: .tiff),
           !tiff.isEmpty,
           tiff.count <= Self.maximumTIFFBytes {
            return .tiff(tiff)
        }
        if let text = item.string(forType: .string),
           let data = text.data(using: .utf8),
           data.count <= ClipboardPayload.maxBytes {
            return .ready(.text, data)
        }
        return nil
    }

    private func write(_ payload: ClipboardPayload) -> Bool {
        let item = NSPasteboardItem()
        switch payload.format {
        case .text:
            guard let text = String(data: payload.data, encoding: .utf8) else { return false }
            item.setString(text, forType: .string)
        case .png:
            guard Self.isValidImage(payload.data, expectedType: UTType.png.identifier) else {
                return false
            }
            item.setData(payload.data, forType: .png)
        }
        pasteboard.clearContents()
        return pasteboard.writeObjects([item])
    }

    private static func isValid(_ payload: ClipboardPayload) -> Bool {
        guard payload.data.count <= ClipboardPayload.maxBytes else {
            return false
        }
        switch payload.format {
        case .text:
            return String(data: payload.data, encoding: .utf8) != nil
        case .png:
            return !payload.data.isEmpty
                && isValidImage(payload.data, expectedType: UTType.png.identifier)
        }
    }

    private static func isValidImage(_ data: Data, expectedType: String) -> Bool {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) > 0,
              let type = CGImageSourceGetType(source) as String? else { return false }
        return type == expectedType
    }

    nonisolated private static func pngData(fromTIFF data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? NSNumber,
              let height = properties[kCGImagePropertyPixelHeight] as? NSNumber,
              width.intValue > 0,
              height.intValue > 0,
              width.intValue <= 32_768,
              height.intValue <= 32_768,
              width.int64Value * height.int64Value <= 100_000_000,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(
            output,
            UTType.png.identifier as CFString,
            1,
            nil
        ) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination), output.length <= ClipboardPayload.maxBytes else {
            return nil
        }
        return output as Data
    }
}
